  var locale = 'zh';
  var listeners = [];

  /** 把 'auto' / 'zh' / 'en' 解析成实际语言 */
  function resolveLocale(preference) {
    if (preference === 'zh' || preference === 'en') return preference;
    var lang = '';
    try {
      lang = (navigator.language || navigator.userLanguage || '').toLowerCase();
    } catch (err) {
      lang = '';
    }
    return lang.indexOf('zh') === 0 ? 'zh' : 'en';
  }

  /**
   * 取一条文案。
   * @param {string} key
   * @param {Object} [params] 插值参数，对应文案里的 {name}
   * @returns {string} 找不到时返回 key 本身，便于发现遗漏
   */
  function t(key, params) {
    var table = DICT[locale] || DICT.zh;
    var value = table[key];
    if (value === undefined) value = (DICT.zh[key] !== undefined ? DICT.zh[key] : key);

    if (params) {
      value = value.replace(/\{(\w+)\}/g, function (match, name) {
        return params[name] !== undefined ? String(params[name]) : match;
      });
    }
    return value;
  }

  /** 填充页面上的静态文案 */
  function apply(root) {
    root = root || document;

    var TEXT_ATTRS = [
      ['data-i18n', 'textContent'],
      ['data-i18n-placeholder', 'placeholder'],
      ['data-i18n-title', 'title'],
      ['data-i18n-aria-label', 'aria-label'],
    ];

    TEXT_ATTRS.forEach(function (pair) {
      var attr = pair[0];
      var prop = pair[1];
      Array.prototype.forEach.call(root.querySelectorAll('[' + attr + ']'), function (node) {
        var value = t(node.getAttribute(attr));
        if (prop === 'textContent') node.textContent = value;
        else node.setAttribute(prop, value);
      });
    });

    // 同步 <html lang>，便于字体与断行规则跟随语言
    if (document.documentElement) {
      document.documentElement.lang = locale === 'zh' ? 'zh-CN' : 'en';
    }
  }

  HA.I18n = {
    LOCALES: ['zh', 'en'],

    setLocale: function (next) {
      if (next !== 'zh' && next !== 'en') return false;
      if (next === locale) return false;
      locale = next;
      listeners.forEach(function (fn) {
        try { fn(locale); } catch (err) { console.warn('[HA] i18n 监听器出错：', err); }
      });
      return true;
    },

    getLocale: function () { return locale; },

    resolve: resolveLocale,

    t: t,

    apply: apply,

    /** 语言变化时重新渲染某些内容（如动态构建的列表） */
    onLocaleChange: function (fn) { listeners.push(fn); },
  };

  // 载入时先按浏览器语言给一个合理默认，调用方随后可用设置覆盖
  locale = resolveLocale('auto');

